#!/usr/bin/env bun
//
// Concatenates the TTY stylesheet into one file, so the browser makes ONE request
// instead of fifteen. Runs last in `bun run build`, after eleventy has copied
// src/styles into dist/.
//
// ── The problem this solves ────────────────────────────────────────────────
//
// src/styles/tty.css is a 1 KB list of `@import` lines — 14 of them when this was
// measured, 13 now that the Silkscreen pin is gone. A browser cannot see those
// imports until it has fetched and parsed that file, so the real stylesheet arrives
// on a SECOND round trip — 80 KB across 15 render-blocking requests, with the first
// paint waiting on the whole chain. Measured on the live site.
//
// Bundling keeps the authoring split exactly as it is. The @import list stays the
// source of truth for cascade order: this reads that list rather than globbing the
// directory, so a file added to tty.css is bundled and a file left out of it is
// left out here too — the one behaviour that matters is order, and the list owns it.
//
// ── Why a new filename ────────────────────────────────────────────────────
//
// The output is styles/tty.bundle.css, not an overwritten styles/tty.css. The
// import list still ships, and several assertions in check-build.sh read it to test
// the authoring contract — that every file it names reaches the bundle, in its order.
// Overwriting it would delete the thing those assertions are about. dist/ also keeps
// the individual files, which 96 further assertions read; browsers never fetch them.
//
// ── Safe because ──────────────────────────────────────────────────────────
//
// Verified before writing this: no imported file contains a nested `@import`, so the
// concatenation is flat, and every `url()` in the CSS is an absolute https URL, so
// moving the rules to a different path cannot break a reference.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const ENTRY_SRC = join(ROOT, "src", "styles", "tty.css");
const OUT = join(ROOT, "dist", "styles", "tty.bundle.css");
const SRC_DIR = join(ROOT, "src", "styles");

if (!existsSync(join(ROOT, "dist", "styles"))) {
  console.error("dist/styles does not exist. Run eleventy first — this bundles its output.");
  process.exit(1);
}

const entry = readFileSync(ENTRY_SRC, "utf8");

// Only real @import statements, in file order. A commented-out import must not be
// picked up, so this matches at the start of a line, allowing leading whitespace.
const imports = [...entry.matchAll(/^\s*@import\s+["']([^"']+)["']\s*;/gm)].map((m) => m[1]);

if (imports.length === 0) {
  console.error("No @import lines found in src/styles/tty.css — refusing to write an empty bundle.");
  process.exit(1);
}

const parts = [
  "/* GENERATED by scripts/bundle-css.mjs — do not edit, do not commit.",
  " *",
  ` * ${imports.length} files concatenated in the order src/styles/tty.css imports them.`,
  " * Edit the sources under src/styles/tty/ and the import list in src/styles/tty.css.",
  " */",
  "",
];

let bytes = 0;
for (const rel of imports) {
  const file = join(SRC_DIR, rel);
  if (!existsSync(file)) {
    console.error(`src/styles/tty.css imports "${rel}", which does not exist.`);
    process.exit(1);
  }
  const css = readFileSync(file, "utf8");
  bytes += Buffer.byteLength(css);
  parts.push(`/* ── ${rel} ─────────────────────────────────────────── */`, css.trimEnd(), "");
}

const out = parts.join("\n");

// A stray @import surviving into the bundle would re-introduce the very waterfall
// this removes, and it would do it silently. Fail rather than ship that.
if (/^\s*@import/m.test(out.replace(/\/\*[\s\S]*?\*\//g, ""))) {
  console.error("The bundle still contains an @import. A source file must have gained one.");
  process.exit(1);
}

writeFileSync(OUT, out);
console.log(`css   styles/tty.bundle.css (${imports.length} files, ${Math.round(bytes / 1024)} KB)`);
